export function findTechnology(name: string): TechnologyCatalogEntry | undefined {
  const normalized = name.trim().toLowerCase();
  if (!normalized) return undefined;
  return technologyCatalog.find(
    (entry) =>
      entry.name.toLowerCase() === normalized ||
      entry.aliases.some((alias) => alias.toLowerCase() === normalized),
  );
}

/** Exact matching keeps Markdown images restricted to the curated, immutable assets. */
export function findTechnologyByIconUrl(url: string): TechnologyCatalogEntry | undefined {
  return technologyCatalog.find((entry) => entry.iconUrl === url);
}
